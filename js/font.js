  // precompute bitmaps for fast fill
  var cache = {};
  function bitmap(ch) {
    if (cache[ch]) return cache[ch];
    var g = G[ch];
    if (!g) g = G["?"];
    var out = [];
    for (var y = 0; y < GLYPH_H; y++) {
      var row = g[y] || ".....";
      for (var x = 0; x < GLYPH_W; x++) {
        if (row.charAt(x) === "#") out.push([x, y]);
      }
    }
    cache[ch] = out;
    return out;
  }

  function drawChar(ctx, ch, x, y, scale) {
    var pts = bitmap(ch);
    for (var i = 0; i < pts.length; i++) {
      ctx.fillRect(x + pts[i][0] * scale, y + pts[i][1] * scale, scale, scale);
    }
  }

  function textWidth(text, scale) {
    var w = 0;
    text = String(text).toUpperCase();
    for (var i = 0; i < text.length; i++) {
      var ch = text.charAt(i);
      if (!G[ch] && ch !== " ") ch = "?";
      w += ADVANCE * scale;
    }
    return w;
  }

  function drawText(ctx, text, x, y, color, scale, opts) {
    opts = opts || {};
    text = String(text).toUpperCase();
    if (scale === undefined) scale = 1;
    if (opts.align === "center") x -= textWidth(text, scale) / 2;
    else if (opts.align === "right") x -= textWidth(text, scale);
    x = Math.round(x); y = Math.round(y);
    if (opts.shadow) {
      var sc = opts.shadowColor || "rgba(0,0,0,0.55)";
      ctx.fillStyle = sc;
      for (var i = 0; i < text.length; i++) {
        drawChar(ctx, text.charAt(i), x + i * ADVANCE * scale + scale, y + scale, scale);
      }
    }
    ctx.fillStyle = color;
    for (var j = 0; j < text.length; j++) {
      drawChar(ctx, text.charAt(j), x + j * ADVANCE * scale, y, scale);
    }
    return textWidth(text, scale);
  }

  function wrap(text, maxW, scale) {
    var words = String(text).toUpperCase().split(/\s+/);
    var lines = [], cur = "";
    for (var i = 0; i < words.length; i++) {
      var test = cur ? cur + " " + words[i] : words[i];
      if (textWidth(test, scale) > maxW && cur) { lines.push(cur); cur = words[i]; }
      else cur = test;
    }
    if (cur) lines.push(cur);
    return lines;
  }

  function drawWrapped(ctx, text, x, y, color, scale, maxW, lineGap, opts) {
    var lines = wrap(text, maxW, scale);
    var lh = (GLYPH_H + (lineGap || 1)) * scale;
    for (var i = 0; i < lines.length; i++) {
      drawText(ctx, lines[i], x, y + i * lh, color, scale, opts);
    }
    return lines.length * lh;
  }

  FG.font = {
    w: textWidth,
    draw: drawText,
    wrap: wrap,
    drawWrapped: drawWrapped,
    lh: function (scale, gap) { return (GLYPH_H + (gap || 1)) * scale; },
    glyphH: GLYPH_H
  };
